// PostgreSQL integration tests run in an isolated, transaction-local schema and always roll back.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pool, testConnection } = require('../server/src/config/database');
const Payment = require('../server/src/models/Payment');
const Stall = require('../server/src/models/Stall');
const Tenant = require('../server/src/models/Tenant');
const User = require('../server/src/models/User');
const results = [];
const done = name => { results.push({ name, passed:true }); console.log('PASS '+name); };
(async () => {
    if (!await testConnection()) throw new Error('Database unavailable');
    const rollback = new Error('QA_ROLLBACK');
    try { await pool.withTransaction(async client => {
        await client.query('CREATE SCHEMA qa_current_integration');
        await client.query('SET LOCAL search_path TO qa_current_integration, public');
        for (const table of ['users','stalls','tenants','payments','applications','notifications','maintenance_requests','announcements']) await client.query(`CREATE TABLE qa_current_integration.${table} (LIKE public.${table} INCLUDING ALL)`);
        const admin = await User.create({ name:'QA Admin',email:'qa-current@example.invalid',password:'TestPass987',role:'admin' });
        const owner = await User.create({ name:'QA Tenant',email:'qa-tenant@example.invalid',password:'TestPass987',role:'tenant' });
        const monthly = await Stall.create({ stall_number:'QA-M',location:'QA',monthly_rent:900,status:'occupied' });
        const daily = await Stall.create({ stall_number:'QA-D',location:'QA',monthly_rent:120,daily_rent:120,rent_type:'daily',status:'occupied' });
        await Tenant.create({user_id:owner,stall_id:monthly,name:'QA Tenant',status:'active',contract_start:'2026-10-01',contract_end:'2026-10-31'});
        const lease = await Tenant.create({user_id:owner,stall_id:daily,name:'QA Tenant',status:'active',contract_start:'2026-10-02',contract_end:'2026-10-04'});
        assert.equal((await Payment.generateMonthlyBills(10,2026)).length,1);
        assert.equal((await Payment.generateMonthlyBills(10,2026)).length,0);
        assert.equal((await Payment.generateDailyBills('2026-10-01')).length,0);
        assert.equal((await Payment.generateDailyBills('2026-10-02')).length,1);
        assert.equal((await Payment.generateDailyBills('2026-10-02')).length,0);
        assert.equal((await Payment.generateDailyBills('2026-10-05')).length,0);
        done('PostgreSQL monthly/daily generation, lease dates and repeat protection');
        await Stall.update(daily,{rent_type:'daily',daily_rent:130,monthly_rent:130,description:'Updated daily stall'});
        assert.equal(Number((await Stall.findById(daily)).daily_rent),130);
        done('PostgreSQL daily stall editing and structured rate persistence');
        const bill = (await Payment.findByTenantId(lease))[0];
        await assert.rejects(Payment.recordOfficePayment(bill.id,119,'OR-QA',admin),/match/);
        const paid = await Payment.recordOfficePayment(bill.id,120,'OR-QA',admin);
        assert.equal(paid.status,'paid');assert.equal(paid.received_by,admin);
        await assert.rejects(Payment.recordOfficePayment(bill.id,120,'OR-QA',admin),/already paid/);
        const next = await Payment.generateDailyBills('2026-10-03');
        await assert.rejects(Payment.recordOfficePayment(next[0].id,130,'or-qa',admin),/already recorded/);
        const feeBill=await Payment.create({tenant_id:lease,stall_id:daily,amount:100,late_fee:10,due_date:'2026-10-04'});
        await assert.rejects(Payment.recordOfficePayment(feeBill,100,'OR-FEE',admin),/match/);
        await Payment.recordOfficePayment(feeBill,110,'OR-FEE',admin);
        assert.equal(Number((await Payment.getStats()).total_collected),230);
        assert.equal(Number((await Payment.getTenantSummary(lease)).total_paid),230);
        done('PostgreSQL office payment balance, cashier audit, duplicate receipt and resubmission');
        const overview=await Payment.getStallsBillingOverview();assert.equal(overview.length,2);assert.equal(overview.find(s=>s.stall_id===daily).rent_type,'daily');
        done('PostgreSQL billing overview with daily and monthly stalls');
        const available = await Stall.create({stall_number:'QA-APP',location:'QA',monthly_rent:500});
        const Application=require('../server/src/models/Application');
        const application=await Application.create({user_id:owner,stall_id:available,full_name:'QA Tenant',email:'qa-tenant@example.invalid',phone:'09999999999',business_name:'QA Shop',business_type:'retail'});
        await require('../server/src/services/applicationReview').review(application,'approved','QA',admin);
        assert.equal((await Application.findById(application)).status,'approved');
        assert.equal((await Stall.findById(available)).status,'occupied');
        done('PostgreSQL application approval, lease creation and notification schema');
        const response=()=>({code:200,status(n){this.code=n;return this;},json(body){this.body=body;return this;}});
        const maintenance=require('../server/src/controllers/maintenanceController');
        const submit=async(body,userId=owner)=>{const res=response();await maintenance.createRequest({body,userId,userRole:'tenant'},res);return res;};
        assert.equal((await submit({title:' ',description:'Leak',stall_id:daily})).code,400);
        assert.equal((await submit({title:'Leak',description:'Pipe',category:'invalid',stall_id:daily})).code,400);
        assert.equal((await submit({title:'Leak',description:'Pipe',stall_id:daily},admin)).code,403);
        const ticket=await submit({title:'Leaking pipe',description:'Pipe under sink',category:'plumbing',priority:'high',stall_id:daily});
        assert.equal(ticket.code,201);assert.equal(ticket.body.data.tenant_id,lease);
        let changed=response();await maintenance.updateStatus({params:{id:ticket.body.data.id},body:{status:'completed',resolution_notes:'Repaired'},userId:admin,userRole:'admin'},changed);assert.equal(changed.code,200);assert.equal(changed.body.data.status,'completed');
        const notices=await require('../server/src/models/Notification').findByUserId(owner);assert.ok(notices.some(n=>n.type==='maintenance_update'));
        const forbidden=response();await maintenance.getRequestById({params:{id:ticket.body.data.id},userId:admin,userRole:'tenant'},forbidden);assert.equal(forbidden.code,403);
        done('PostgreSQL tenant maintenance submission, validation, completion, notification and ownership');
        const Announcement=require('../server/src/models/Announcement');
        const announcement=await Announcement.create({author_id:admin,title:'QA notice',content:'QA content',target_audience:'tenants'});
        assert.equal((await Announcement.findById(announcement)).title,'QA notice');
        await Announcement.update(announcement,{title:'Updated QA',author_id:owner});
        assert.equal((await Announcement.findById(announcement)).author_id,admin);
        assert.ok((await Announcement.findAll({target_audience:'tenants'})).some(a=>a.id===announcement));
        assert.equal(await Announcement.delete(announcement),true);
        done('PostgreSQL announcement create/read/update/delete and protected author');
        const users=require('../server/src/controllers/userController');
        for(const [id,body] of [[owner,{role:'staff'}],[admin,{role:'tenant'}],[admin,{is_active:false}]]){const res=response();await users.updateUser({params:{id},body,userId:admin},res);assert.equal(res.code,400);}
        done('Staff assignment and self-removal of admin access rejected');
        throw rollback;
    }); } catch(error) { if(error !== rollback) throw error; }
    const schemas=await pool.query("SELECT schema_name FROM information_schema.schemata WHERE schema_name='qa_current_integration'");assert.equal(schemas.rows.length,0);
    done('All QA data and schema rolled back; production rows preserved');
    fs.writeFileSync(path.join(__dirname,'current-postgres-results.json'),JSON.stringify(results,null,2));
})().then(()=>process.exit(0)).catch(error=>{console.error(error.message);process.exit(1)});
